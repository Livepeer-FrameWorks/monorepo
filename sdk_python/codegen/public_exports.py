"""Writes livepeer_frameworks/_generated/public_exports.py, the export list
of livepeer_frameworks.graphql.

The public module exports the raw GraphQLClient, every enum and every input
type ariadne-codegen generated (so each type a generated client method takes
is importable), and the domain models: the classes of the hand-written
fragments in pkg/graphql/public/fragments (Stream, and nested models such as
StreamPlaybackPolicy). Fragments on types implementing the Error interface
are left out, because expect_result raises those members as ResultError.
Operation-specific response containers (CreateStreamCreateStreamStream) and
the default-operation fragments (StreamDefault) are not exported.

make graphql-sdk-py runs this from sdk_python/ after both ariadne-codegen
runs, since the async run writes the final enums and input types."""

from __future__ import annotations

import ast
import sys
from pathlib import Path

from graphql import FragmentDefinitionNode, GraphQLObjectType, build_schema, parse

_SDK = Path(__file__).resolve().parents[1]
_REPO = _SDK.parent
_SCHEMA = _REPO / "pkg/graphql/public/schema.public.graphql"
_FRAGMENTS = _REPO / "pkg/graphql/public/fragments"
_GENERATED = _SDK / "src/livepeer_frameworks/_generated"
_PACKAGE = _GENERATED / "graphql"
_OUTPUT = _GENERATED / "public_exports.py"

_SUFFIX = "Fields"
_ERROR_INTERFACE = "Error"


def _classes(path: Path) -> dict[str, ast.ClassDef]:
    tree = ast.parse(path.read_text())
    return {node.name: node for node in tree.body if isinstance(node, ast.ClassDef)}


def _referenced_names(node: ast.ClassDef) -> set[str]:
    """Class names a class body refers to, as names or as the quoted forward
    references ariadne-codegen writes."""
    names: set[str] = set()
    for child in ast.walk(node):
        if isinstance(child, ast.Name):
            names.add(child.id)
        elif isinstance(child, ast.Constant) and isinstance(child.value, str) and child.value.isidentifier():
            names.add(child.value)
    return names


def _domain_roots() -> list[str]:
    """The model names of the hand-written fragments: StreamFields becomes
    Stream, as codegen/forward_compat.py renames them."""
    schema = build_schema(_SCHEMA.read_text())
    roots: list[str] = []
    for path in sorted(_FRAGMENTS.rglob("*.graphql")):
        for definition in parse(path.read_text()).definitions:
            if not isinstance(definition, FragmentDefinitionNode):
                continue
            name = definition.name.value
            if not name.endswith(_SUFFIX):
                raise ValueError(f"{path}: fragment {name} does not end in {_SUFFIX}")
            type_ = schema.get_type(definition.type_condition.name.value)
            if isinstance(type_, GraphQLObjectType) and any(
                iface.name == _ERROR_INTERFACE for iface in type_.interfaces
            ):
                continue
            roots.append(name[: -len(_SUFFIX)])
    return roots


def _domain_models(fragments: dict[str, ast.ClassDef]) -> set[str]:
    """Each root model and the nested models ariadne-codegen generated for
    its selections (named after the root, StreamPlaybackPolicy)."""
    models: set[str] = set()
    for root in _domain_roots():
        if root not in fragments:
            raise ValueError(f"fragment model {root} is not in {_PACKAGE / 'fragments.py'}")
        pending = [root]
        while pending:
            name = pending.pop()
            if name in models:
                continue
            models.add(name)
            for ref in _referenced_names(fragments[name]):
                if ref in fragments and ref.startswith(root) and ref not in models:
                    pending.append(ref)
    return models


def _import_block(module: str, names: list[str]) -> str:
    body = "".join(f"    {name},\n" for name in names)
    return f"from .graphql.{module} import (\n{body})\n"


def render() -> str:
    groups = {
        "client": ["GraphQLClient"],
        "enums": sorted(_classes(_PACKAGE / "enums.py")),
        "fragments": sorted(_domain_models(_classes(_PACKAGE / "fragments.py"))),
        "input_types": sorted(_classes(_PACKAGE / "input_types.py")),
    }
    seen: dict[str, str] = {}
    for module, names in groups.items():
        for name in names:
            if name in seen:
                raise ValueError(f"{name} is exported from both {seen[name]} and {module}")
            seen[name] = module

    parts = [
        "# Code generated by sdk_python/codegen/public_exports.py (make graphql-sdk-py). DO NOT EDIT.\n",
        '"""The export list of livepeer_frameworks.graphql."""\n\n',
        "from .graphql.client import GraphQLClient\n",
    ]
    parts += [_import_block(module, names) for module, names in groups.items() if module != "client"]
    parts.append("\n__all__ = [\n")
    parts += [f'    "{name}",\n' for name in sorted(seen)]
    parts.append("]\n")
    return "".join(parts)


def main() -> int:
    _OUTPUT.write_text(render())
    return 0


if __name__ == "__main__":
    sys.exit(main())
