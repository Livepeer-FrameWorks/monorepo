package main

import (
	"bytes"
	"context"
	"encoding/json"
	"flag"
	"fmt"
	"os"
	"os/exec"
	"strings"
	"time"

	"github.com/Livepeer-FrameWorks/monorepo/pkg/vodupload"
)

func main() {
	check := flag.Bool("check", false, "fail when generated upload formats are stale")
	output := flag.String("output", "../website_application/src/lib/uploads/formats.ts", "output TypeScript file")
	flag.Parse()
	extensions := vodupload.UploadExtensions()
	encoded, err := json.Marshal(extensions)
	if err != nil {
		panic(err)
	}
	labels := make([]string, len(extensions))
	for i, extension := range extensions {
		labels[i] = strings.ToUpper(extension)
	}
	help, err := json.Marshal(strings.Join(labels, ", "))
	if err != nil {
		panic(err)
	}
	generated := []byte(fmt.Sprintf(`// Generated by scripts/vodformats; edit pkg/vodupload/formats.go.
export const VOD_UPLOAD_EXTENSIONS = %s as const;
export const VOD_UPLOAD_ACCEPT = VOD_UPLOAD_EXTENSIONS.map((extension) => "." + extension).join(",");
export const VOD_UPLOAD_FORMATS_LABEL = %s;
export const VOD_UPLOAD_MAX_FILENAME_BYTES = %d;

export function isSupportedVodFilename(filename: string): boolean {
  const extension = filename.slice(filename.lastIndexOf(".") + 1).toLowerCase();
  return filename.includes(".") && VOD_UPLOAD_EXTENSIONS.some((supported) => supported === extension);
}
`, encoded, help, vodupload.MaxFilenameBytes))
	ctx, cancel := context.WithTimeout(context.Background(), time.Minute)
	defer cancel()
	formatter := exec.CommandContext(ctx, "pnpm", "exec", "prettier", "--stdin-filepath", *output)
	formatter.Stdin = bytes.NewReader(generated)
	formatted, err := formatter.Output()
	if err != nil {
		fmt.Fprintf(os.Stderr, "format upload contracts: %v\n", err)
		os.Exit(1)
	}
	generated = formatted
	if *check {
		current, err := os.ReadFile(*output)
		if err != nil || !bytes.Equal(current, generated) {
			fmt.Fprintln(os.Stderr, "VOD upload formats are stale; run make vod-formats")
			os.Exit(1)
		}
		return
	}
	if err := os.WriteFile(*output, generated, 0o644); err != nil {
		panic(err)
	}
}
