// Default operations give every SDK a typed method for every part of the
// public schema a caller can address with arguments, without a hand-kept list.
//
// Targets. Every public, non-deprecated field of the Query, Mutation, and
// Subscription types is a target. So is every non-deprecated field that takes
// arguments on a type reached from Query through singular (non-list) object
// fields: the operation selects the path from the root down to it, and every
// argument of every field on that path becomes a variable. A type is visited
// once, at its shortest distance from Query (fields in schema order break
// ties), so each such field gets exactly one path and the schema's cycles end
// the walk. An argument field on an object type that walk does not reach but
// that implements the Node interface is a target through Query.node: the
// operation selects node(id: $id) { __typename ... on <Type> { <field>(...) } }
// and its key names the type after node
// (query.node.InfrastructureNode.metricsConnection). Its document carries a
// "# @target <key>" annotation (targetAnnotation), since operationTarget
// alone would read it as query.node. Other argument fields reached only
// through lists, unions, or interfaces, and paths below Mutation and
// Subscription roots, are not targets: an operation there would run once per
// list item or re-run the mutation. A target whose default selection is
// empty (a namespace such as Query.analytics, whose data sits behind
// argument fields) gets no operation; its argument fields do.
//
// Selection. A target returning an object type spreads that type's generated
// fragment <Type>DefaultFields: its scalar and enum fields plus its
// argument-free object, union, and interface fields to depth 2 (the fields of
// the type's children and grandchildren; grandchildren select only scalars
// and enums). A connection (edges { cursor node } plus pageInfo) selects
// edges { cursor node { ... } } with the node shaped like a target, pageInfo
// through PageInfoDefaultFields, and its other fields as an object would;
// nodes is left out because edges carries the same records. A union or
// interface selects __typename and each member's fragment; a member field
// whose type differs from the other members' is aliased there
// (memberAliases). Fields that take
// arguments are never part of a selection (they are targets of their own),
// nor are deprecated fields and arguments, nor @experimental fields
// (selectableByDefault). An experimental field is reached through its own
// operation when it is a root or takes arguments; that operation is
// experimental (targetExperimental). An argument-free experimental field
// below a root has no generated operation: callers select it through the
// TypeScript select client or a custom document. The lint rejects any
// operation, hand-written included, that selects an @experimental field
// without having an experimental target.
//
// Overrides. A hand-written operation in pkg/graphql/public/{queries,
// mutations,subscriptions} replaces the default operation of the target it
// addresses (resolveTarget: its @target annotation, else the path
// operationTarget infers); the generator emits nothing for that target.
//
// Names. Query operations are Get<Field>, mutations and subscriptions
// <Field>, in PascalCase. A nested query target is Get<Field> when no other
// query target ends in a field of that name, otherwise Get followed by every
// field of its path. A target through Query.node is Get<Type><Field>
// (GetInfrastructureNodeMetricsConnection). A name that equals a public
// schema type gets the operation kind as suffix, since the Go and Python
// SDKs declare enums and inputs under the schema's type names.
//
// Targets file. generated/targets.json maps every operation, hand-written
// and generated, to its target; the SDK code generators read it to document
// each operation with its target field's description. Its experimental map
// lists the operations whose target path has an @experimental field; the
// SDKs mark them experimental in their doc comments, and api-compat lets a
// released line drop them (the field may go by its until release).
const (
	generatedOpsDir     = publicDir + "/generated"
	defaultSelectDepth  = 2
	defaultFragmentName = "DefaultFields"
	pageInfoType        = "PageInfo"
)

var generatedOpsHeader = "# Code generated by scripts/sdkcontract from " + publicSchemaPath + " (make generate-ops). DO NOT EDIT.\n" +
	"# Default operations: one per public root field and per argument-taking field below Query or on a Node type;\n" +
	"# hand-written operations in queries/, mutations/, and subscriptions/ replace them.\n"

// opTarget is a field a default operation addresses: the path of fields from
// a root type down to it.
type opTarget struct {
	Kind ast.Operation
	Path []*ast.FieldDefinition
	// On is the member type the selection of Path[0] narrows to before
	// Path[1:]; set only for targets through Query.node.
	On string
}

func (t opTarget) key() string {
	names := make([]string, 0, len(t.Path)+1)
	for i, f := range t.Path {
		names = append(names, f.Name)
		if i == 0 && t.On != "" {
			names = append(names, t.On)
		}
	}
	return string(t.Kind) + "." + strings.Join(names, ".")
}

func (t opTarget) field() *ast.FieldDefinition { return t.Path[len(t.Path)-1] }

func rootTypes(schema *ast.Schema) []struct {
	kind ast.Operation
	def  *ast.Definition
} {
	return []struct {
		kind ast.Operation
		def  *ast.Definition
	}{{ast.Query, schema.Query}, {ast.Mutation, schema.Mutation}, {ast.Subscription, schema.Subscription}}
}

func isDeprecated(dirs ast.DirectiveList) bool { return dirs.ForName("deprecated") != nil }

// selectable reports whether f can be a target or lie on a target's path.
// An @experimental field can: its operation is then experimental
// (targetExperimental).
func selectable(f *ast.FieldDefinition) bool {
	return !strings.HasPrefix(f.Name, "__") && !isDeprecated(f.Directives)
}

// selectableByDefault reports whether f belongs in a default selection. An
// @experimental field never does, so no operation that is stable by its
// target selects a field that may be removed within the line.
func selectableByDefault(f *ast.FieldDefinition) bool {
	_, _, experimental := experimentalMark(f)
	return selectable(f) && !experimental
}

// opTargets returns every target of the schema in a deterministic order, and
// the argument fields that are not targets because a list, union, or
// interface other than Query.node is the only way to reach them from Query.
func opTargets(schema *ast.Schema) (targets []opTarget, listOnly []string) {
	for _, root := range rootTypes(schema) {
		if root.def == nil {
			continue
		}
		for _, f := range root.def.Fields {
			if selectable(f) {
				targets = append(targets, opTarget{Kind: root.kind, Path: []*ast.FieldDefinition{f}})
			}
		}
	}
	if schema.Query == nil {
		return targets, nil
	}

	type visit struct {
		def  *ast.Definition
		path []*ast.FieldDefinition
	}
	visited := map[string]bool{schema.Query.Name: true}
	queue := []visit{{def: schema.Query}}
	for len(queue) > 0 {
		cur := queue[0]
		queue = queue[1:]
		for _, f := range cur.def.Fields {
			if !selectable(f) {
				continue
			}
			path := append(append([]*ast.FieldDefinition{}, cur.path...), f)
			if len(cur.path) > 0 && len(f.Arguments) > 0 {
				targets = append(targets, opTarget{Kind: ast.Query, Path: path})
			}
			next := schema.Types[f.Type.Name()]
			if f.Type.Elem != nil || next == nil || next.Kind != ast.Object || visited[next.Name] {
				continue
			}
			visited[next.Name] = true
			queue = append(queue, visit{def: next, path: path})
		}
	}

	// Argument fields on object types a public field returns but the walk
	// did not reach: targets through Query.node when the type implements
	// Node, custom selection otherwise.
	node := nodeField(schema)
	for _, name := range sortedKeys(schema.Types) {
		def := schema.Types[name]
		if def.Kind != ast.Object || def.BuiltIn || visited[name] || isRootType(schema, def) {
			continue
		}
		viaNode := node != nil && implements(def, node.Type.Name())
		for _, f := range def.Fields {
			if !selectable(f) || len(f.Arguments) == 0 {
				continue
			}
			if viaNode {
				targets = append(targets, opTarget{Kind: ast.Query, Path: []*ast.FieldDefinition{node, f}, On: name})
				continue
			}
			listOnly = append(listOnly, name+"."+f.Name)
		}
	}
	sort.Strings(listOnly)
	return targets, listOnly
}

// nodeField returns Query.node when the schema has the Relay node(id: ID!)
// field returning an interface, and nil otherwise.
func nodeField(schema *ast.Schema) *ast.FieldDefinition {
	f := schema.Query.Fields.ForName("node")
	if f == nil || !selectable(f) || f.Type.Elem != nil || len(f.Arguments) != 1 || f.Arguments[0].Name != "id" {
		return nil
	}
	if def := schema.Types[f.Type.Name()]; def == nil || def.Kind != ast.Interface {
		return nil
	}
	return f
}

func isRootType(schema *ast.Schema, def *ast.Definition) bool {
	return def == schema.Query || def == schema.Mutation || def == schema.Subscription
}

// selNode is one selection of a generated document: a field (with optional
// arguments), a fragment spread, or an inline fragment.
type selNode struct {
	text     string
	children []*selNode
}

func leaf(text string) *selNode { return &selNode{text: text} }

// selectionBuilder renders default selections and collects the fragments
// they spread.
type selectionBuilder struct {
	schema    *ast.Schema
	fragments map[string][]*selNode
	fragType  map[string]string
}

func newSelectionBuilder(schema *ast.Schema) *selectionBuilder {
	return &selectionBuilder{schema: schema, fragments: map[string][]*selNode{}, fragType: map[string]string{}}
}

// connectionNode returns the node type of a connection type: an object with
// pageInfo: PageInfo and edges whose items carry cursor and node.
func (b *selectionBuilder) connectionNode(def *ast.Definition) *ast.Definition {
	if def.Kind != ast.Object {
		return nil
	}
	edges, pageInfo := def.Fields.ForName("edges"), def.Fields.ForName("pageInfo")
	if edges == nil || pageInfo == nil || edges.Type.Elem == nil || pageInfo.Type.Name() != pageInfoType {
		return nil
	}
	edge := b.schema.Types[edges.Type.Name()]
	if edge == nil || edge.Kind != ast.Object || edge.Fields.ForName("cursor") == nil || edge.Fields.ForName("node") == nil {
		return nil
	}
	return b.schema.Types[edge.Fields.ForName("node").Type.Name()]
}

// members returns the object types an abstract type can resolve to, sorted
// by name for interfaces (union members keep their declared order).
func (b *selectionBuilder) members(def *ast.Definition) []*ast.Definition {
	if def.Kind == ast.Union {
		out := make([]*ast.Definition, 0, len(def.Types))
		for _, name := range def.Types {
			out = append(out, b.schema.Types[name])
		}
		return out
	}
	out := append([]*ast.Definition{}, b.schema.GetPossibleTypes(def)...)
	sort.Slice(out, func(i, j int) bool { return out[i].Name < out[j].Name })
	return out
}

// fields is the default selection of object type def at depth: its scalar
// and enum fields, and its argument-free composite fields while their depth
// stays within defaultSelectDepth. The fields in aliased are selected as
// <type><Field> (memberAliases).
func (b *selectionBuilder) fields(def *ast.Definition, depth int, aliased map[string]bool) []*selNode {
	connection := b.connectionNode(def) != nil
	var out []*selNode
	for _, f := range def.Fields {
		if !selectableByDefault(f) || len(f.Arguments) > 0 || (connection && f.Name == "nodes") {
			continue
		}
		node := b.fieldSelection(f, depth)
		if node == nil {
			continue
		}
		if aliased[f.Name] {
			node.text = lowerFirst(def.Name) + pascal(f.Name) + ": " + f.Name
		}
		out = append(out, node)
	}
	return out
}

func (b *selectionBuilder) fieldSelection(f *ast.FieldDefinition, depth int) *selNode {
	named := b.schema.Types[f.Type.Name()]
	switch named.Kind {
	case ast.Scalar, ast.Enum:
		return leaf(f.Name)
	}
	if depth+1 > defaultSelectDepth {
		return nil
	}
	sub := b.nested(named, depth+1)
	if len(sub) == 0 {
		return nil
	}
	return &selNode{text: f.Name, children: sub}
}

func (b *selectionBuilder) nested(def *ast.Definition, depth int) []*selNode {
	if def.Kind == ast.Object {
		return b.fields(def, depth, nil)
	}
	return b.memberSelections(def, depth, false)
}

// memberSelections selects __typename and each member of abstract type def:
// the member's fragment when shared is set, its fields inline otherwise. A
// member with aliased fields (memberAliases) spreads its own fragment for
// this abstract type, <Member>In<Abstract>DefaultFields.
func (b *selectionBuilder) memberSelections(def *ast.Definition, depth int, shared bool) []*selNode {
	out := []*selNode{leaf("__typename")}
	aliases := b.memberAliases(def)
	for _, m := range b.members(def) {
		if shared {
			name := m.Name + defaultFragmentName
			if len(aliases[m.Name]) > 0 {
				name = m.Name + "In" + def.Name + defaultFragmentName
			}
			if spread := b.fragment(name, m, aliases[m.Name]); spread != nil {
				out = append(out, spread)
			}
			continue
		}
		if fs := b.fields(m, depth, aliases[m.Name]); len(fs) > 0 {
			out = append(out, &selNode{text: "... on " + m.Name, children: fs})
		}
	}
	return out
}

// memberAliases returns, per member of abstract type def, the fields it
// selects under an alias. Members are selected side by side, and GraphQL
// rejects two fields of one response name with different types
// (MediaPlacementError.code is MediaPlacementErrorCode!, AuthError.code is
// String). For each field name the type most members declare (the first
// member's on a tie) keeps the name; a member declaring another type selects
// the field as <member><Field> (mediaPlacementErrorCode). Aliases apply only
// where the member is selected as part of def, so Stream.streamId keeps its
// name everywhere but where Stream is one of the many Node implementations.
func (b *selectionBuilder) memberAliases(def *ast.Definition) map[string]map[string]bool {
	ms := b.members(def)
	counts := map[string]map[string]int{}
	order := map[string][]string{}
	for _, m := range ms {
		for _, f := range m.Fields {
			if !selectableByDefault(f) || len(f.Arguments) > 0 {
				continue
			}
			t := f.Type.String()
			if counts[f.Name] == nil {
				counts[f.Name] = map[string]int{}
			}
			if counts[f.Name][t] == 0 {
				order[f.Name] = append(order[f.Name], t)
			}
			counts[f.Name][t]++
		}
	}
	out := map[string]map[string]bool{}
	for field, byType := range counts {
		if len(byType) < 2 {
			continue
		}
		canonical := order[field][0]
		for _, t := range order[field] {
			if byType[t] > byType[canonical] {
				canonical = t
			}
		}
		for _, m := range ms {
			f := m.Fields.ForName(field)
			if f == nil || !selectableByDefault(f) || len(f.Arguments) > 0 || f.Type.String() == canonical {
				continue
			}
			if out[m.Name] == nil {
				out[m.Name] = map[string]bool{}
			}
			out[m.Name][field] = true
		}
	}
	return out
}

func lowerFirst(s string) string {
	if s == "" {
		return s
	}
	return strings.ToLower(s[:1]) + s[1:]
}

// fragment returns a spread of the fragment name holding def's default
// selection with the given aliases, or nil when the type has nothing to
// select.
func (b *selectionBuilder) fragment(name string, def *ast.Definition, aliased map[string]bool) *selNode {
	if _, ok := b.fragments[name]; !ok {
		fs := b.fields(def, 0, aliased)
		if len(fs) == 0 {
			return nil
		}
		b.fragments[name] = fs
		b.fragType[name] = def.Name
	}
	return leaf("..." + name)
}

// branches reports whether a selection, fragments expanded, holds anything
// but a single composite field.
func (b *selectionBuilder) branches(sel []*selNode) bool {
	names := map[string]bool{}
	composite := false
	var walk func([]*selNode)
	walk = func(nodes []*selNode) {
		for _, n := range nodes {
			switch {
			case strings.HasPrefix(n.text, "... on "):
				walk(n.children)
			case strings.HasPrefix(n.text, "..."):
				walk(b.fragments[strings.TrimPrefix(n.text, "...")])
			default:
				names[n.text] = true
				composite = composite || len(n.children) > 0
			}
		}
	}
	walk(sel)
	return len(names) != 1 || !composite
}

// targetSelection is the selection of a target field returning def; empty
// for scalars, enums, and namespaces.
func (b *selectionBuilder) targetSelection(def *ast.Definition) []*selNode {
	switch def.Kind {
	case ast.Scalar, ast.Enum:
		return nil
	case ast.Union, ast.Interface:
		return b.memberSelections(def, 0, true)
	}
	node := b.connectionNode(def)
	if node == nil {
		if spread := b.fragment(def.Name+defaultFragmentName, def, nil); spread != nil {
			return []*selNode{spread}
		}
		return nil
	}
	var out []*selNode
	for _, f := range def.Fields {
		if !selectableByDefault(f) || len(f.Arguments) > 0 || f.Name == "nodes" {
			continue
		}
		switch f.Name {
		case "edges":
			nodeSel := b.targetSelection(node)
			if len(nodeSel) == 0 {
				nodeSel = []*selNode{leaf("__typename")}
			}
			out = append(out, &selNode{text: "edges", children: []*selNode{leaf("cursor"), {text: "node", children: nodeSel}}})
		case "pageInfo":
			out = append(out, &selNode{text: "pageInfo", children: []*selNode{b.fragment(pageInfoType+defaultFragmentName, b.schema.Types[pageInfoType], nil)}})
		default:
			if sel := b.fieldSelection(f, 0); sel != nil {
				out = append(out, sel)
			}
		}
	}
	return out
}

// isNamespace reports whether a target returning def has an empty default
// selection: an object whose data sits behind argument fields, such as the
// type of Query.analytics.
func (b *selectionBuilder) isNamespace(def *ast.Definition) bool {
	return def.Kind != ast.Scalar && def.Kind != ast.Enum && len(b.targetSelection(def)) == 0
}

// namespaceRoots returns the keys (query.analytics) of the root fields whose
// targets are namespaces: they get no operation of their own, their argument
// fields do.
func namespaceRoots(schema *ast.Schema) map[string]bool {
	b := newSelectionBuilder(schema)
	out := map[string]bool{}
	targets, _ := opTargets(schema)
	for _, t := range targets {
		if len(t.Path) == 1 && b.isNamespace(schema.Types[t.field().Type.Name()]) {
			out[t.key()] = true
		}
	}
	return out
}

// defaultOp is one generated operation before printing.
type defaultOp struct {
	Name   string
	Target opTarget
	Vars   []opVariable
	// Args holds, per path field, its arguments as name: $variable pairs.
	Args      [][]string
	Selection []*selNode
}

type opVariable struct {
	Name    string
	Type    *ast.Type
	Default *ast.Value
}

// reservedVariable holds the Go and Python keywords: genqlient and
// ariadne-codegen turn variables into function parameters of those names.
var reservedVariable = map[string]bool{}

func init() {
	for _, w := range strings.Fields(`break case chan const continue default defer else fallthrough for func go goto if
		import interface map package range return select struct switch type var
		and as assert async await class def del elif except finally from global in is lambda nonlocal not or pass
		raise try while with yield`) {
		reservedVariable[w] = true
	}
}

// variables assigns a variable to every non-deprecated argument on the path.
// The target field's arguments keep their names; an argument whose name is
// taken, or is reserved, becomes <field><Argument>.
func variables(t opTarget) ([]opVariable, [][]string, error) {
	taken := map[string]bool{}
	args := make([][]string, len(t.Path))
	perField := make([][]opVariable, len(t.Path))
	for i := len(t.Path) - 1; i >= 0; i-- {
		f := t.Path[i]
		for _, a := range f.Arguments {
			if isDeprecated(a.Directives) {
				if a.Type.NonNull && a.DefaultValue == nil {
					return nil, nil, fmt.Errorf("%s: argument %s.%s is deprecated but required", t.key(), f.Name, a.Name)
				}
				continue
			}
			name := a.Name
			if taken[name] || reservedVariable[name] {
				name = f.Name + pascal(a.Name)
			}
			if taken[name] {
				return nil, nil, fmt.Errorf("%s: no free variable name for argument %s.%s", t.key(), f.Name, a.Name)
			}
			taken[name] = true
			typ := a.Type
			if a.DefaultValue != nil && typ.NonNull {
				// A nullable variable with the schema default keeps the
				// default when the caller leaves it out.
				c := *typ
				c.NonNull = false
				typ = &c
			}
			perField[i] = append(perField[i], opVariable{Name: name, Type: typ, Default: a.DefaultValue})
			args[i] = append(args[i], a.Name+": $"+name)
		}
	}
	var vars []opVariable
	for _, vs := range perField {
		vars = append(vars, vs...)
	}
	return vars, args, nil
}

func pascal(s string) string {
	if s == "" {
		return s
	}
	return strings.ToUpper(s[:1]) + s[1:]
}

// opNames assigns the default operation names described at the top of this
// file.
func opNames(schema *ast.Schema, targets []opTarget) map[string]string {
	lastField := map[string]int{}
	for _, t := range targets {
		if t.Kind == ast.Query && t.On == "" {
			lastField[t.field().Name]++
		}
	}
	names := map[string]string{}
	for _, t := range targets {
		var name string
		switch {
		case t.On != "":
			name = "Get" + t.On + pascal(t.field().Name)
		case t.Kind == ast.Query && (len(t.Path) == 1 || lastField[t.field().Name] == 1):
			name = "Get" + pascal(t.field().Name)
		case t.Kind == ast.Query:
			name = "Get"
			for _, f := range t.Path {
				name += pascal(f.Name)
			}
		default:
			name = pascal(t.field().Name)
		}
		if schema.Types[name] != nil {
			name += pascal(string(t.Kind))
		}
		names[t.key()] = name
	}
	return names
}

// generateDefaultOps renders the default operations and their fragments for
// every target that no hand-written operation replaces, keyed by output path.
func generateDefaultOps(schema *ast.Schema, handWritten []operation) (map[string]string, []defaultOp, error) {
	overridden := map[string]string{}
	for _, op := range handWritten {
		overridden[op.Target] = op.Name
	}
	targets, _ := opTargets(schema)
	names := opNames(schema, targets)
	b := newSelectionBuilder(schema)

	var ops []defaultOp
	for _, t := range targets {
		if _, ok := overridden[t.key()]; ok {
			continue
		}
		def := schema.Types[t.field().Type.Name()]
		if b.isNamespace(def) {
			continue
		}
		sel := b.targetSelection(def)
		if len(sel) > 0 && !b.branches(sel) {
			// operationTarget would read a lone composite field as part of
			// the path; __typename keeps the target where it is.
			sel = append([]*selNode{leaf("__typename")}, sel...)
		}
		vars, args, err := variables(t)
		if err != nil {
			return nil, nil, err
		}
		ops = append(ops, defaultOp{Name: names[t.key()], Target: t, Vars: vars, Args: args, Selection: sel})
	}

	byKind := map[ast.Operation]*strings.Builder{}
	for _, kind := range []ast.Operation{ast.Query, ast.Mutation, ast.Subscription} {
		byKind[kind] = &strings.Builder{}
	}
	sort.SliceStable(ops, func(i, j int) bool { return ops[i].Name < ops[j].Name })
	for _, op := range ops {
		w := byKind[op.Target.Kind]
		w.WriteString("\n")
		printOperation(w, op)
	}
	var frags strings.Builder
	for _, name := range sortedKeys(b.fragments) {
		frags.WriteString("\n")
		fmt.Fprintf(&frags, "fragment %s on %s {\n", name, b.fragType[name])
		printSelection(&frags, b.fragments[name], 1)
		frags.WriteString("}\n")
	}
	files := map[string]string{
		generatedOpsDir + "/queries.graphql":       generatedOpsHeader + byKind[ast.Query].String(),
		generatedOpsDir + "/mutations.graphql":     generatedOpsHeader + byKind[ast.Mutation].String(),
		generatedOpsDir + "/subscriptions.graphql": generatedOpsHeader + byKind[ast.Subscription].String(),
		generatedOpsDir + "/fragments.graphql":     generatedOpsHeader + frags.String(),
	}
	return files, ops, nil
}

func printOperation(w *strings.Builder, op defaultOp) {
	if op.Target.On != "" {
		w.WriteString("# " + targetAnnotation + " " + op.Target.key() + "\n")
	}
	w.WriteString(string(op.Target.Kind) + " " + op.Name)
	if len(op.Vars) > 0 {
		w.WriteString("(\n")
		for _, v := range op.Vars {
			if v.Default != nil {
				// genqlient sends a nil pointer as null, which replaces the
				// schema default; omitempty leaves the variable out instead.
				w.WriteString("  # @genqlient(omitempty: true)\n")
				fmt.Fprintf(w, "  $%s: %s = %s\n", v.Name, v.Type.String(), v.Default.String())
				continue
			}
			fmt.Fprintf(w, "  $%s: %s\n", v.Name, v.Type.String())
		}
		w.WriteString(")")
	}
	w.WriteString(" {\n")
	indent := 1
	for i, f := range op.Target.Path {
		line := strings.Repeat("  ", indent) + f.Name
		if len(op.Args[i]) > 0 {
			line += "(" + strings.Join(op.Args[i], ", ") + ")"
		}
		last := i == len(op.Target.Path)-1
		if last && len(op.Selection) == 0 {
			w.WriteString(line + "\n")
			break
		}
		w.WriteString(line + " {\n")
		indent++
		if i == 0 && op.Target.On != "" {
			w.WriteString(strings.Repeat("  ", indent) + "__typename\n")
			w.WriteString(strings.Repeat("  ", indent) + "... on " + op.Target.On + " {\n")
			indent++
		}
		if last {
			printSelection(w, op.Selection, indent)
		}
	}
	for indent > 1 {
		indent--
		w.WriteString(strings.Repeat("  ", indent) + "}\n")
	}
	w.WriteString("}\n")
}

func printSelection(w *strings.Builder, nodes []*selNode, indent int) {
	pad := strings.Repeat("  ", indent)
	for _, n := range nodes {
		if len(n.children) == 0 {
			w.WriteString(pad + n.text + "\n")
			continue
		}
		w.WriteString(pad + n.text + " {\n")
		printSelection(w, n.children, indent+1)
		w.WriteString(pad + "}\n")
	}
}

// generatedSources turns rendered files into parser sources.
func generatedSources(files map[string]string) []*ast.Source {
	var out []*ast.Source
	for _, p := range sortedKeys(files) {
		out = append(out, &ast.Source{Name: filepath.ToSlash(p), Input: files[p]})
	}
	return out
}

// buildDefaultOps generates the default operations for the working tree and
// checks the complete operation set: the loader rules (unique operation,
// fragment, and target names) and the public-operation lint, which validates
// every document against the public schema.
func buildDefaultOps(repo string) (map[string]string, []defaultOp, []operation, error) {
	schema, err := loadPublicSchema(repo, headRef)
	if err != nil {
		return nil, nil, nil, err
	}
	handSources, err := operationSources(repo, false)
	if err != nil {
		return nil, nil, nil, err
	}
	handWritten, err := parseOperations(schema, handSources)
	if err != nil {
		return nil, nil, nil, err
	}
	files, ops, err := generateDefaultOps(schema, handWritten)
	if err != nil {
		return nil, nil, nil, err
	}
	all, err := parseOperations(schema, append(handSources, generatedSources(files)...))
	if err != nil {
		return nil, nil, nil, err
	}
	if problems := lintOperations(schema, all); len(problems) > 0 {
		return nil, nil, nil, failList("default operations violate the contract", problems)
	}
	targets, err := renderTargets(all)
	if err != nil {
		return nil, nil, nil, err
	}
	files[targetsFile] = targets
	return files, ops, all, nil
}

// targetsFile maps each public operation to its target for the SDK code
// generators (npm_api/codegen/descriptions.mjs, sdk_go/tools/genclient,
// sdk_python/codegen/forward_compat.py), so none of them re-derives targets.
const targetsFile = generatedOpsDir + "/targets.json"

func renderTargets(ops []operation) (string, error) {
	type experimentalEntry struct {
		experimentalTarget
		// Note is the sentence every SDK appends to the operation's doc
		// comment, so the three generators word it identically.
		Note string `json:"note"`
	}
	targets := map[string]string{}
	experimental := map[string]experimentalEntry{}
	for _, op := range ops {
		targets[op.Name] = op.Target
		if op.Experimental.Until != "" {
			experimental[op.Name] = experimentalEntry{experimentalTarget: op.Experimental, Note: experimentalNote(op.Experimental)}
		}
	}
	data, err := json.MarshalIndent(struct {
		Description  string                       `json:"description"`
		Targets      map[string]string            `json:"targets"`
		Experimental map[string]experimentalEntry `json:"experimental"`
	}{
		Description:  "Generated by scripts/sdkcontract (make generate-ops); do not edit. targets: the field each public operation addresses: kind.field.field, with a member type name after a field of union or interface type. experimental: the operations whose target path has an @experimental field, with that field's until release, reason, and the note the SDKs add to the operation's doc comment.",
		Targets:      targets,
		Experimental: experimental,
	}, "", "  ")
	if err != nil {
		return "", err
	}
	return string(data) + "\n", nil
}

// experimentalNote is the doc-comment sentence for an operation on an
// @experimental field.
func experimentalNote(e experimentalTarget) string {
	reason := strings.TrimSpace(e.Reason)
	if reason != "" && !strings.HasSuffix(reason, ".") {
		reason += "."
	}
	note := "Experimental until " + e.Until + ":"
	if reason != "" {
		note += " " + reason
	}
	return note + " A later SDK release of this line may change or remove this operation."
}

func runGenerateOps(repo string, check bool) error {
	files, ops, all, err := buildDefaultOps(repo)
	if err != nil {
		return err
	}
	for _, op := range ops {
		if op.Target.key() != targetOf(all, op.Name) {
			return fmt.Errorf("%s: selects %s, not its target %s", op.Name, targetOf(all, op.Name), op.Target.key())
		}
	}
	stale, err := writeOrCheck(repo, files, check)
	if err != nil {
		return err
	}
	if len(stale) > 0 {
		return failList("default operations are stale; run make generate-ops", stale)
	}
	counts := map[ast.Operation]int{}
	nested := 0
	for _, op := range ops {
		counts[op.Target.Kind]++
		if len(op.Target.Path) > 1 {
			nested++
		}
	}
	fmt.Printf("sdkcontract: %d default operations (%d queries, %d of them nested; %d mutations; %d subscriptions), %d hand-written\n",
		len(ops), counts[ast.Query], nested, counts[ast.Mutation], counts[ast.Subscription], len(all)-len(ops))
	return nil
}

func targetOf(ops []operation, name string) string {
	for _, op := range ops {
		if op.Name == name {
			return op.Target
		}
	}
	return ""
}
