package main

import (
	"encoding/json"
	"fmt"
	"sort"

	"github.com/vektah/gqlparser/v2"
	"github.com/vektah/gqlparser/v2/ast"
)

// operationsFixturePath holds, for every public operation, variables and a
// response synthesized from the working-tree schema. Every SDK's tests send
// each generated operation through a mock transport answering with it, so a
// generated type that cannot decode a schema-shaped response fails CI.
const operationsFixturePath = "sdk_conformance/operations.json"

type operationsFixture struct {
	Description string             `json:"description"`
	Operations  []operationFixture `json:"operations"`
}

type operationFixture struct {
	Name      string         `json:"name"`
	Kind      string         `json:"kind"`
	Variables map[string]any `json:"variables"`
	Response  map[string]any `json:"response"`
}

var scalarSamples = map[string]any{
	"ID":       "id-1",
	"String":   "text",
	"Int":      1,
	"Float":    1.5,
	"Boolean":  true,
	"Time":     "2026-09-19T14:03:27Z",
	"JSON":     map[string]any{"key": "value"},
	"Currency": "EUR",
	"Money":    "12.50",
}

func renderOperationsFixture(schema *ast.Schema, ops []operation) (string, error) {
	fixture := operationsFixture{
		Description: "Generated by scripts/sdkcontract from pkg/graphql/public and the working-tree schema; do not edit. For each operation: the required variables and a response whose data follows the operation's selection, choosing the first selected non-error member of each union.",
	}
	for _, op := range ops {
		doc, errs := gqlparser.LoadQueryWithRules(schema, op.Document, nil)
		if len(errs) > 0 {
			return "", fmt.Errorf("%s: %s", op.Name, errs.Error())
		}
		m := &mocker{schema: schema}
		o := doc.Operations[0]
		vars := map[string]any{}
		for _, v := range o.VariableDefinitions {
			if v.Type.NonNull && v.DefaultValue == nil {
				vars[v.Variable] = m.inputValue(v.Type)
			}
		}
		var root *ast.Definition
		switch o.Operation {
		case ast.Query:
			root = schema.Query
		case ast.Mutation:
			root = schema.Mutation
		case ast.Subscription:
			root = schema.Subscription
		}
		data := m.object(o.SelectionSet, root)
		delete(data, "__typename")
		fixture.Operations = append(fixture.Operations, operationFixture{
			Name:      op.Name,
			Kind:      op.Kind,
			Variables: vars,
			Response:  map[string]any{"data": data},
		})
	}
	sort.Slice(fixture.Operations, func(i, j int) bool { return fixture.Operations[i].Name < fixture.Operations[j].Name })
	out, err := json.MarshalIndent(fixture, "", "  ")
	if err != nil {
		return "", err
	}
	return string(out) + "\n", nil
}

type mocker struct {
	schema *ast.Schema
}

func (m *mocker) inputValue(t *ast.Type) any {
	if t.Elem != nil {
		return []any{m.inputValue(t.Elem)}
	}
	def := m.schema.Types[t.NamedType]
	switch def.Kind {
	case ast.Enum:
		return firstEnumValue(def)
	case ast.InputObject:
		obj := map[string]any{}
		for _, f := range def.Fields {
			if f.Type.NonNull && f.DefaultValue == nil {
				obj[f.Name] = m.inputValue(f.Type)
			}
		}
		return obj
	default:
		return scalarSamples[def.Name]
	}
}

func firstEnumValue(def *ast.Definition) string {
	for _, v := range def.EnumValues {
		if v.Directives.ForName("deprecated") == nil {
			return v.Name
		}
	}
	return def.EnumValues[0].Name
}

func (m *mocker) value(t *ast.Type, set ast.SelectionSet) any {
	if t.Elem != nil {
		return []any{m.value(t.Elem, set)}
	}
	def := m.schema.Types[t.NamedType]
	switch def.Kind {
	case ast.Enum:
		return firstEnumValue(def)
	case ast.Object:
		return m.object(set, def)
	case ast.Union, ast.Interface:
		return m.object(set, m.pickMember(def, set))
	default:
		return scalarSamples[def.Name]
	}
}

// pickMember chooses the concrete type of an abstract field: the first
// selected member that is not an error type, then the first selected member.
func (m *mocker) pickMember(abstract *ast.Definition, set ast.SelectionSet) *ast.Definition {
	var selected []string
	for _, sel := range set {
		switch s := sel.(type) {
		case *ast.InlineFragment:
			selected = append(selected, s.TypeCondition)
		case *ast.FragmentSpread:
			selected = append(selected, s.Definition.TypeCondition)
		}
	}
	possible := m.schema.GetPossibleTypes(abstract)
	isPossible := func(name string) *ast.Definition {
		for _, p := range possible {
			if p.Name == name {
				return p
			}
		}
		return nil
	}
	for _, name := range selected {
		if def := isPossible(name); def != nil && !implements(def, errorInterface) {
			return def
		}
	}
	for _, name := range selected {
		if def := isPossible(name); def != nil {
			return def
		}
	}
	return possible[0]
}

func (m *mocker) object(set ast.SelectionSet, concrete *ast.Definition) map[string]any {
	out := map[string]any{}
	for _, sel := range set {
		switch s := sel.(type) {
		case *ast.Field:
			if s.Name == "__typename" {
				out[s.Alias] = concrete.Name
				continue
			}
			mergeValue(out, s.Alias, m.value(s.Definition.Type, s.SelectionSet))
		case *ast.InlineFragment:
			if s.TypeCondition == "" || m.applies(s.TypeCondition, concrete) {
				mergeInto(out, m.object(s.SelectionSet, concrete))
			}
		case *ast.FragmentSpread:
			if m.applies(s.Definition.TypeCondition, concrete) {
				mergeInto(out, m.object(s.Definition.SelectionSet, concrete))
			}
		}
	}
	return out
}

func (m *mocker) applies(condition string, concrete *ast.Definition) bool {
	if condition == concrete.Name {
		return true
	}
	cond := m.schema.Types[condition]
	if cond == nil || (cond.Kind != ast.Interface && cond.Kind != ast.Union) {
		return false
	}
	for _, p := range m.schema.GetPossibleTypes(cond) {
		if p.Name == concrete.Name {
			return true
		}
	}
	return false
}

func mergeInto(dst, src map[string]any) {
	for k, v := range src {
		mergeValue(dst, k, v)
	}
}

func mergeValue(dst map[string]any, key string, v any) {
	existing, ok := dst[key]
	if !ok {
		dst[key] = v
		return
	}
	a, aok := existing.(map[string]any)
	b, bok := v.(map[string]any)
	if aok && bok {
		mergeInto(a, b)
		return
	}
	al, alok := existing.([]any)
	bl, blok := v.([]any)
	if alok && blok && len(al) == 1 && len(bl) == 1 {
		if ao, ok := al[0].(map[string]any); ok {
			if bo, ok := bl[0].(map[string]any); ok {
				mergeInto(ao, bo)
				return
			}
		}
	}
	dst[key] = v
}
