// Visibility is declared in pkg/graphql/schema.graphql with two metadata
// directives that the gateway skips at runtime:
//
//	@internal(reason)            the field needs a credential a tenant cannot
//	                             hold; it is not part of the public schema
//	@experimental(reason, until) the field is public but not stable yet;
//	                             until is the platform release by which it
//	                             graduates or is removed
//
// The public schema is the contract: the SDK generators, the operation lint,
// the compatibility checks, and the API reference all read it, never the full
// schema.
const (
	internalDirective     = "internal"
	experimentalDirective = "experimental"
	publicSchemaPath      = "pkg/graphql/public/schema.public.graphql"
)

const publicSchemaHeader = "# Code generated by scripts/sdkcontract from " + schemaPath + " (make generate-public-schema). DO NOT EDIT.\n" +
	"# The public GraphQL contract: fields marked @internal and the types only they reach are left out.\n\n"

// privateDescriptionMarkers are description phrases of fields that need a
// private credential. A public field whose description says so is missing
// its @internal directive.
var privateDescriptionMarkers = []string{"service token required", "every field requires the platform_operator grant"}

// internalReason returns the reason of a field's @internal directive.
func internalReason(field *ast.FieldDefinition) (string, bool) {
	d := field.Directives.ForName(internalDirective)
	if d == nil {
		return "", false
	}
	return directiveString(d, "reason"), true
}

// experimentalMark returns the reason and until of a field's @experimental
// directive.
func experimentalMark(field *ast.FieldDefinition) (reason, until string, ok bool) {
	d := field.Directives.ForName(experimentalDirective)
	if d == nil {
		return "", "", false
	}
	return directiveString(d, "reason"), directiveString(d, "until"), true
}

func directiveString(d *ast.Directive, name string) string {
	if arg := d.Arguments.ForName(name); arg != nil && arg.Value != nil {
		return arg.Value.Raw
	}
	return ""
}

// hiddenField reports whether field is left out of the public schema.
func hiddenField(field *ast.FieldDefinition) bool {
	if strings.HasPrefix(field.Name, "__") {
		return true
	}
	_, internal := internalReason(field)
	return internal
}

// loadPublicSchema returns the public schema of the schema at ref.
func loadPublicSchema(repo, ref string) (*ast.Schema, error) {
	full, err := loadFullSchema(repo, ref)
	if err != nil {
		return nil, err
	}
	public, err := publicSchema(full)
	if err != nil {
		return nil, fmt.Errorf("public schema at %s: %w", ref, err)
	}
	return public, nil
}

// publicSchema returns full without its @internal fields and without the
// types no longer reachable from the root operation types. It is parsed back
// from renderPublicSchema, so it is exactly the committed artifact and is
// validated as a schema of its own.
func publicSchema(full *ast.Schema) (*ast.Schema, error) {
	text, err := renderPublicSchema(full)
	if err != nil {
		return nil, err
	}
	public, gerr := gqlparser.LoadSchema(&ast.Source{Name: publicSchemaPath, Input: text})
	if gerr != nil {
		return nil, fmt.Errorf("filtered schema is invalid: %w", gerr)
	}
	return public, nil
}

// renderPublicSchema prints the public schema as SDL: types sorted by name,
// fields in source order, descriptions and deprecations kept.
func renderPublicSchema(full *ast.Schema) (string, error) {
	if problems := visibilityProblems(full); len(problems) > 0 {
		return "", failList("schema visibility directives are inconsistent", problems)
	}
	reachable := publicTypes(full)

	out := &ast.Schema{Types: map[string]*ast.Definition{}, Directives: map[string]*ast.DirectiveDefinition{}}
	for name := range reachable {
		def := *full.Types[name]
		def.Fields = nil
		for _, field := range full.Types[name].Fields {
			if !hiddenField(field) {
				def.Fields = append(def.Fields, field)
			}
		}
		out.Types[name] = &def
	}
	for name, dir := range full.Directives {
		if name != internalDirective {
			out.Directives[name] = dir
		}
	}

	// A root type whose every field is internal leaves the public schema; an
	// object type without fields is not valid SDL.
	root := &ast.SchemaDefinition{Description: full.Description}
	for _, op := range []struct {
		kind ast.Operation
		def  *ast.Definition
	}{{ast.Query, full.Query}, {ast.Mutation, full.Mutation}, {ast.Subscription, full.Subscription}} {
		if op.def == nil {
			continue
		}
		if len(out.Types[op.def.Name].Fields) == 0 {
			delete(out.Types, op.def.Name)
			continue
		}
		root.OperationTypes = append(root.OperationTypes, &ast.OperationTypeDefinition{Operation: op.kind, Type: op.def.Name})
	}

	blocks := []*ast.SchemaDocument{{Schema: ast.SchemaDefinitionList{root}}}
	for _, name := range sortedKeys(out.Directives) {
		if dir := out.Directives[name]; dir.Position == nil || dir.Position.Src == nil || !dir.Position.Src.BuiltIn {
			blocks = append(blocks, &ast.SchemaDocument{Directives: ast.DirectiveDefinitionList{dir}})
		}
	}
	for _, name := range sortedKeys(out.Types) {
		blocks = append(blocks, &ast.SchemaDocument{Definitions: ast.DefinitionList{out.Types[name]}})
	}
	parts := make([]string, 0, len(blocks))
	for _, block := range blocks {
		var buf bytes.Buffer
		formatter.NewFormatter(&buf, formatter.WithIndent("  ")).FormatSchemaDocument(block)
		parts = append(parts, strings.TrimRight(buf.String(), "\n"))
	}
	// The formatter indents the empty lines of block-string descriptions;
	// block-string parsing drops that whitespace, so trimming it leaves every
	// description unchanged.
	lines := strings.Split(publicSchemaHeader+strings.Join(parts, "\n\n"), "\n")
	for i, line := range lines {
		lines[i] = strings.TrimRight(line, " \t")
	}
	return strings.Join(lines, "\n") + "\n", nil
}

func sortedKeys[V any](m map[string]V) []string {
	keys := make([]string, 0, len(m))
	for k := range m {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	return keys
}

// visibilityProblems checks the directive arguments the gateway cannot check:
// reasons are present, until is a release version, and a field is not both
// internal and experimental.
func visibilityProblems(full *ast.Schema) []string {
	var problems []string
	for name, def := range full.Types {
		if def.BuiltIn || strings.HasPrefix(name, "__") {
			continue
		}
		for _, field := range def.Fields {
			key := name + "." + field.Name
			reason, internal := internalReason(field)
			if internal && strings.TrimSpace(reason) == "" {
				problems = append(problems, key+": @internal needs a reason")
			}
			expReason, until, experimental := experimentalMark(field)
			if !experimental {
				continue
			}
			if internal {
				problems = append(problems, key+": a field is either @internal or @experimental")
			}
			if strings.TrimSpace(expReason) == "" {
				problems = append(problems, key+": @experimental needs a reason")
			}
			if _, ok := parseSemver(until); !ok {
				problems = append(problems, fmt.Sprintf("%s: @experimental until %q is not a release version vMAJOR.MINOR.PATCH", key, until))
			}
		}
	}
	sort.Strings(problems)
	return problems
}

// undeclaredPrivateFields lists public fields whose description states a
// private credential requirement, which means a missing @internal. Only the
// working tree is held to it: released schemas predate the directive.
func undeclaredPrivateFields(full *ast.Schema) []string {
	var problems []string
	for name, def := range full.Types {
		if def.BuiltIn || strings.HasPrefix(name, "__") {
			continue
		}
		for _, field := range def.Fields {
			if _, internal := internalReason(field); internal {
				continue
			}
			lower := strings.Join(strings.Fields(strings.ToLower(field.Description)), " ")
			for _, marker := range privateDescriptionMarkers {
				if strings.Contains(lower, marker) {
					problems = append(problems, fmt.Sprintf("%s.%s: description says %q but the field is not @internal", name, field.Name, marker))
				}
			}
		}
	}
	sort.Strings(problems)
	return problems
}

// publicTypes returns the named types a client can reach from the root
// operation types without crossing an @internal field: output and argument
// types of public fields, input fields, implemented interfaces, union
// members, and the implementations of an interface a public field returns.
// An interface reached only through an implements clause does not make its
// other implementations reachable, since no field can return them.
func publicTypes(full *ast.Schema) map[string]bool {
	reachable := map[string]bool{}
	returned := map[string]bool{}
	var queue []string
	add := func(name string) {
		if reachable[name] || isBuiltinType(name) || full.Types[name] == nil || full.Types[name].BuiltIn {
			return
		}
		reachable[name] = true
		queue = append(queue, name)
	}
	addReturned := func(name string) {
		add(name)
		def := full.Types[name]
		if def == nil || def.Kind != ast.Interface || returned[name] {
			return
		}
		returned[name] = true
		for _, impl := range full.PossibleTypes[name] {
			add(impl.Name)
		}
	}
	for _, root := range []*ast.Definition{full.Query, full.Mutation, full.Subscription} {
		if root != nil {
			add(root.Name)
		}
	}
	for _, dir := range full.Directives {
		if dir.Name == internalDirective {
			continue
		}
		for _, arg := range dir.Arguments {
			add(arg.Type.Name())
		}
	}
	for len(queue) > 0 {
		def := full.Types[queue[0]]
		queue = queue[1:]
		for _, iface := range def.Interfaces {
			add(iface)
		}
		for _, member := range def.Types {
			add(member)
		}
		for _, field := range def.Fields {
			if hiddenField(field) {
				continue
			}
			if def.Kind == ast.InputObject {
				add(field.Type.Name())
			} else {
				addReturned(field.Type.Name())
			}
			for _, arg := range field.Arguments {
				add(arg.Type.Name())
			}
		}
	}
	return reachable
}

// experimentalField is one @experimental field of the public schema.
type experimentalField struct {
	Field, Reason string
	Until         semver
}

// experimentalFields lists the @experimental fields of a public schema,
// sorted by field.
func experimentalFields(public *ast.Schema) []experimentalField {
	var out []experimentalField
	for name, def := range public.Types {
		if def.BuiltIn {
			continue
		}
		for _, field := range def.Fields {
			reason, until, ok := experimentalMark(field)
			if !ok {
				continue
			}
			v, _ := parseSemver(until)
			out = append(out, experimentalField{Field: name + "." + field.Name, Reason: reason, Until: v})
		}
	}
	sort.Slice(out, func(i, j int) bool { return out[i].Field < out[j].Field })
	return out
}

// expiredExperimental lists the experimental fields whose until release is at
// or below current.
func expiredExperimental(fields []experimentalField, current semver) []string {
	var expired []string
	for _, f := range fields {
		if !current.Less(f.Until) {
			expired = append(expired, fmt.Sprintf("%s: experimental until %s, and the pending release is %s; remove @experimental or the field", f.Field, f.Until, current))
		}
	}
	return expired
}

func runPublicSchema(repo string, check bool) error {
	full, err := loadFullSchema(repo, headRef)
	if err != nil {
		return err
	}
	if problems := undeclaredPrivateFields(full); len(problems) > 0 {
		return failList("fields need @internal", problems)
	}
	text, err := renderPublicSchema(full)
	if err != nil {
		return err
	}
	public, gerr := gqlparser.LoadSchema(&ast.Source{Name: publicSchemaPath, Input: text})
	if gerr != nil {
		return fmt.Errorf("filtered schema is invalid: %w", gerr)
	}
	stale, err := writeOrCheck(repo, map[string]string{publicSchemaPath: text}, check)
	if err != nil {
		return err
	}
	if len(stale) > 0 {
		return failList("public schema is stale; run make generate-public-schema", stale)
	}
	fmt.Printf("sdkcontract: public schema has %d of %d types\n", countNamedTypes(public), countNamedTypes(full))
	return nil
}

func countNamedTypes(schema *ast.Schema) int {
	n := 0
	for name, def := range schema.Types {
		if !def.BuiltIn && !strings.HasPrefix(name, "__") {
			n++
		}
	}
	return n
}

// runExperimental prints every experimental field and fails when the pending
// platform release has reached a field's until release. The pending release
// is the one the working tree ships as (cli/internal/releases/catalog.yaml,
// or the latest tag when that is newer), because until names the platform
// release that serves the schema, not an SDK line.
func runExperimental(repo string) error {
	public, err := loadPublicSchema(repo, headRef)
	if err != nil {
		return err
	}
	matrix, err := loadMatrix(repo)
	if err != nil {
		return err
	}
	fields := experimentalFields(public)
	for _, f := range fields {
		fmt.Printf("experimental: %s until %s — %s\n", f.Field, f.Until, f.Reason)
	}
	if expired := expiredExperimental(fields, matrix.Pending); len(expired) > 0 {
		return failList("experimental fields past their until release", expired)
	}
	fmt.Printf("sdkcontract: %d experimental fields, none due by %s\n", len(fields), matrix.Pending)
	return nil
}
