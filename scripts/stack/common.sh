#!/usr/bin/env bash
# Shared slot setup for the production-shaped stack (scripts/stack/up.sh,
# down.sh, verify.sh). Source it; it exports what every plain `docker compose`
# call needs to address this slot, so existing compose-based scripts become
# slot-aware without edits.
#
#   STACK_SLOT=N   independent stack N on one Docker engine (default 1)
#
# Each slot is its own compose project (fw-stack-N) on its own subnet, with
# every fixed container_name and host port reset, so 2-3 slots coexist.
# A slot number belongs to one checkout at a time per Docker engine (see
# stack_require_slot below).

stack_repo_root="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
STACK_SLOT="${STACK_SLOT:-1}"
case "$STACK_SLOT" in
  '' | *[!0-9]*) echo "ERROR: STACK_SLOT must be a small positive integer, got '$STACK_SLOT'" >&2; exit 2 ;;
esac
if [ "$STACK_SLOT" -lt 1 ] || [ "$STACK_SLOT" -gt 200 ]; then
  echo "ERROR: STACK_SLOT must be between 1 and 200" >&2
  exit 2
fi

export STACK_SLOT
export COMPOSE_PROJECT_NAME="fw-stack-$STACK_SLOT"
# Durable S3 (docker-compose.stack.yml): Ceph RGW where the engine can run its
# amd64-only demo image, the pinned SeaweedFS otherwise. STACK_S3=ceph|seaweed
# overrides the choice.
if [ -z "${STACK_S3:-}" ]; then
  case "$(docker version --format '{{.Server.Arch}}' 2>/dev/null)" in
    amd64 | x86_64) STACK_S3=ceph ;;
    *) STACK_S3=seaweed ;;
  esac
fi
case "$STACK_S3" in
  ceph | seaweed) ;;
  *) echo "ERROR: STACK_S3 must be ceph or seaweed, got '$STACK_S3'" >&2; exit 2 ;;
esac
export STACK_S3
export COMPOSE_PROFILES="edge,two-cell,stack,stack-s3-$STACK_S3,network-observations"
# The go-livepeer gateway trusts X-Forwarded-For only from this subnet, which is
# why each slot pins its own.
export STACK_SUBNET="${STACK_SUBNET:-10.231.$STACK_SLOT.0/24}"
export STACK_EDGE_IMAGE="frameworks-edge:stack-$STACK_SLOT"
export STACK_STATE_DIR="$stack_repo_root/.stack/slot-$STACK_SLOT"
mkdir -p "$STACK_STATE_DIR"

# Each slot runs on its own generated environment (up.sh writes it), never the
# workspace .env: services load it through ENV_FILE and compose interpolates
# from it through COMPOSE_ENV_FILES.
# The seeded demo user; up.sh gives it this stack-only password (lib.sh uses
# the same defaults inside the runner).
export STACK_DEMO_EMAIL="${STACK_DEMO_EMAIL:-demo@frameworks.network}"
export STACK_DEMO_PASSWORD="${STACK_DEMO_PASSWORD:-stack-demo-password}"

export ENV_FILE="$STACK_STATE_DIR/stack.env"
export COMPOSE_ENV_FILES="$ENV_FILE"
# compose refuses a missing env_file even for `config`; up.sh fills it.
[ -e "$ENV_FILE" ] || : >"$ENV_FILE"

# The reset overlay is generated from the service list rather than kept by hand,
# so a service added to docker-compose.yml can never keep a fixed name or port.
stack_write_reset_overlay() {
  local services
  services="$(COMPOSE_FILE="$stack_repo_root/docker-compose.yml:$stack_repo_root/docker-compose.stack.yml" \
    docker compose --project-directory "$stack_repo_root" config --services)" || return 1
  {
    echo "# Generated by scripts/stack/common.sh for slot $STACK_SLOT; do not edit."
    echo "services:"
    while IFS= read -r svc; do
      [ -n "$svc" ] || continue
      printf '  %s:\n    container_name: !reset null\n    ports: !reset []\n' "$svc"
    done <<<"$services"
  } >"$STACK_STATE_DIR/reset.yml"
}

stack_write_reset_overlay || { echo "ERROR: could not list compose services for the reset overlay" >&2; exit 1; }
export COMPOSE_FILE="$stack_repo_root/docker-compose.yml:$stack_repo_root/docker-compose.stack.yml:$STACK_STATE_DIR/reset.yml"

stack_compose() { docker compose --project-directory "$stack_repo_root" "$@"; }

# Slot ownership. The project name, subnet and edge image tag all derive from
# the slot number alone, so two checkouts on one Docker engine cannot share a
# slot: the second would recreate or tear down the first one's containers. A
# slot belongs to the checkout whose stack is in it, which Docker records as
# compose's working_dir label on every container of the project. Before the
# first container exists, up.sh's claim file (checkout and PID, kept per engine
# under /tmp so every user of a shared host sees it) names the owner for as long
# as that up.sh runs.
stack_canonical_dir() { (cd -P "$1" 2>/dev/null && pwd) || printf '%s\n' "$1"; }

stack_slot_claim_file() {
  local engine
  engine="$(docker info --format '{{.ID}}' 2>/dev/null | tr -cd 'A-Za-z0-9-')"
  printf '/tmp/frameworks-stack-slots/%s/slot-%s\n' "${engine:-default}" "$STACK_SLOT"
}

# Prints the other checkout that holds this slot; prints nothing when the slot
# is free or already this checkout's.
stack_slot_foreign_owner() {
  local self dir claim owner pid
  self="$(stack_canonical_dir "$stack_repo_root")"
  while IFS= read -r dir; do
    [ -n "$dir" ] || continue
    [ "$(stack_canonical_dir "$dir")" = "$self" ] && continue
    printf '%s\n' "$dir"
    return 0
  done < <(docker ps -a --filter "label=com.docker.compose.project=$COMPOSE_PROJECT_NAME" \
    --format '{{.Label "com.docker.compose.project.working_dir"}}' 2>/dev/null | sort -u)
  claim="$(stack_slot_claim_file)"
  [ -s "$claim" ] || return 0
  owner="$(sed -n 's/^checkout=//p' "$claim")"
  pid="$(sed -n 's/^pid=//p' "$claim")"
  [ -n "$owner" ] && [ "$(stack_canonical_dir "$owner")" != "$self" ] || return 0
  case "$pid" in '' | *[!0-9]*) return 0 ;; esac
  if kill -0 "$pid" 2>/dev/null || ps -p "$pid" >/dev/null 2>&1; then
    printf '%s (bring-up PID %s)\n' "$owner" "$pid"
  fi
}

# Fails, naming the owner, when another checkout holds this slot.
stack_require_slot() {
  local owner
  owner="$(stack_slot_foreign_owner)"
  [ -z "$owner" ] && return 0
  echo "ERROR: stack slot $STACK_SLOT ($COMPOSE_PROJECT_NAME) belongs to the checkout at $owner; use another STACK_SLOT, or free it with make stack-down from that checkout" >&2
  return 1
}

# Claims the slot for this checkout and the calling shell's PID ($$), or fails
# like stack_require_slot. The check and the write run under a host-wide lock
# so two checkouts starting the same slot at once cannot both pass.
stack_claim_slot() {
  local claim rc=0
  claim="$(stack_slot_claim_file)"
  mkdir -p "${claim%/*}" && chmod 1777 /tmp/frameworks-stack-slots "${claim%/*}" 2>/dev/null
  exec 9>>"$claim.lock" || { echo "ERROR: cannot open the slot lock $claim.lock" >&2; return 1; }
  chmod 666 "$claim.lock" 2>/dev/null
  if command -v flock >/dev/null 2>&1; then
    flock -w 60 9 || rc=1
  else
    perl -MFcntl=:flock -e 'open(my $fh, ">>&=9") or exit 1; flock($fh, LOCK_EX) or exit 1' || rc=1
  fi
  if [ "$rc" -ne 0 ]; then
    echo "ERROR: could not take the slot lock $claim.lock" >&2
  elif stack_require_slot; then
    printf 'checkout=%s\npid=%s\n' "$stack_repo_root" "$$" >"$claim" || rc=1
    chmod 666 "$claim" 2>/dev/null
  else
    rc=1
  fi
  exec 9>&-
  return "$rc"
}

# Gateway TLS: go-livepeer instances are reached as https://<infra fqdn>, exactly
# as Foghorn addresses a physical gateway in production. Mist's broadcaster
# client does not verify peers, so a per-slot self-signed pair is enough.
stack_ensure_gateway_certs() {
  local dir="$STACK_STATE_DIR/certs" cell fqdn
  mkdir -p "$dir"
  for cell in a b; do
    fqdn="livepeer-gateway.stack-lp-$cell.infra.frameworks.network"
    [ -s "$dir/$cell.crt" ] && [ -s "$dir/$cell.key" ] && continue
    openssl req -x509 -newkey rsa:2048 -nodes -days 30 -subj "/CN=$fqdn" \
      -addext "subjectAltName=DNS:$fqdn" -keyout "$dir/$cell.key" -out "$dir/$cell.crt" >/dev/null 2>&1 ||
      { echo "ERROR: openssl could not create the gateway certificate for $fqdn" >&2; return 1; }
  done
}

# Cell A's public control name, as production names a cell's Foghorn
# (foghorn.<cluster>.<root>), and the stack CA that signs the cell wildcard its
# TLS fronts serve. Unlike Mist, Helmsman verifies the chain and the name, so
# the edge is given foghorn-ca.crt as GRPC_TLS_CA_PATH.
stack_ensure_foghorn_control_certs() {
  local dir="$STACK_STATE_DIR/certs" domain="demo-media.stack.frameworks.network" ext
  mkdir -p "$dir"
  [ -s "$dir/foghorn-ca.crt" ] && [ -s "$dir/foghorn-a.crt" ] && [ -s "$dir/foghorn-a.key" ] && return 0
  ext="$(mktemp)"
  printf 'subjectAltName=DNS:*.%s\nbasicConstraints=critical,CA:FALSE\nkeyUsage=critical,digitalSignature,keyEncipherment\nextendedKeyUsage=serverAuth\n' \
    "$domain" >"$ext"
  if ! openssl req -x509 -newkey rsa:2048 -nodes -days 30 -subj "/CN=FrameWorks stack slot $STACK_SLOT CA" \
    -addext "basicConstraints=critical,CA:TRUE" -addext "keyUsage=critical,keyCertSign,cRLSign" \
    -keyout "$dir/foghorn-ca.key" -out "$dir/foghorn-ca.crt" >/dev/null 2>&1 ||
    ! openssl req -newkey rsa:2048 -nodes -subj "/CN=*.$domain" \
      -keyout "$dir/foghorn-a.key" -out "$dir/foghorn-a.csr" >/dev/null 2>&1 ||
    ! openssl x509 -req -in "$dir/foghorn-a.csr" -CA "$dir/foghorn-ca.crt" -CAkey "$dir/foghorn-ca.key" \
      -CAcreateserial -days 30 -extfile "$ext" -out "$dir/foghorn-a.crt" >/dev/null 2>&1; then
    rm -f "$ext" "$dir"/foghorn-*
    echo "ERROR: openssl could not create the Foghorn control certificates for *.$domain" >&2
    return 1
  fi
  rm -f "$ext" "$dir/foghorn-a.csr"
}
