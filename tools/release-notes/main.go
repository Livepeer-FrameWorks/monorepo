// Command release-notes drafts a GitHub Release body from the conventional
// commit subjects between a tag and a revision. It fills the New, Hardened,
// Fixes, Build / infra, and Docs sections defined in
// docs/standards/release-notes.md and leaves the Upgrade section as a
// placeholder, because operator steps have to be written from the diff rather
// than from commit subjects. Every bullet is raw material to verify and
// rewrite before publishing.
//
//	go run . --since v0.3.4 [--until HEAD] [--version v0.3.5] [--repo ../..]
package main

import (
	"bytes"
	"context"
	"flag"
	"fmt"
	"os"
	"os/exec"
	"regexp"
	"strings"
)

const (
	fieldSep  = "\x1f"
	recordSep = "\x1e"
)

var subjectPattern = regexp.MustCompile(`^([a-z]+)(?:\(([^)]*)\))?(!)?: (.+)$`)

// sectionOrder is the body section order from docs/standards/release-notes.md.
var sectionOrder = []string{"New", "Hardened", "Fixes", "Build / infra", "Docs", "Unclassified"}

type commit struct {
	Hash    string
	Subject string
}

type entry struct {
	Summary  string
	Scope    string
	Hash     string
	Breaking bool
}

func main() {
	since := flag.String("since", "", "previous release tag (required)")
	until := flag.String("until", "HEAD", "last revision to include")
	releaseVersion := flag.String("version", "", "version for the draft title (defaults to a placeholder)")
	repo := flag.String("repo", "../..", "repository root")
	flag.Parse()
	if *since == "" {
		fmt.Fprintln(os.Stderr, "release-notes: --since is required")
		os.Exit(2)
	}

	commits, err := readCommits(*repo, *since, *until)
	if err != nil {
		fmt.Fprintln(os.Stderr, "release-notes:", err)
		os.Exit(1)
	}
	fmt.Print(render(*releaseVersion, *since, *until, commits))
}

func readCommits(repo, since, until string) ([]commit, error) {
	cmd := exec.CommandContext(context.Background(), "git", "-C", repo, "log", "--no-merges", "--format=%h"+fieldSep+"%s"+recordSep, since+".."+until)
	var stderr bytes.Buffer
	cmd.Stderr = &stderr
	out, err := cmd.Output()
	if err != nil {
		return nil, fmt.Errorf("git log %s..%s: %w: %s", since, until, err, strings.TrimSpace(stderr.String()))
	}
	var commits []commit
	for record := range strings.SplitSeq(string(out), recordSep) {
		record = strings.TrimSpace(record)
		if record == "" {
			continue
		}
		hash, subject, ok := strings.Cut(record, fieldSep)
		if !ok {
			continue
		}
		commits = append(commits, commit{Hash: hash, Subject: strings.TrimSpace(subject)})
	}
	return commits, nil
}

// classify maps a commit to its release-note section. ok is false for commits
// that never appear in release notes, such as the release preparation commit.
func classify(c commit) (section string, e entry, ok bool) {
	m := subjectPattern.FindStringSubmatch(c.Subject)
	if m == nil {
		return "Unclassified", entry{Summary: c.Subject, Hash: c.Hash}, true
	}
	kind, scope, breaking, summary := m[1], m[2], m[3] == "!", m[4]
	e = entry{Summary: summary, Scope: scope, Hash: c.Hash, Breaking: breaking}
	switch kind {
	case "feat":
		return "New", e, true
	case "refactor", "perf":
		return "Hardened", e, true
	case "fix":
		return "Fixes", e, true
	case "docs":
		return "Docs", e, true
	case "chore":
		if scope == "release" {
			return "", entry{}, false
		}
		return "Build / infra", e, true
	case "build", "ci", "test", "style":
		return "Build / infra", e, true
	default:
		return "Unclassified", entry{Summary: c.Subject, Hash: c.Hash}, true
	}
}

func render(releaseVersion, since, until string, commits []commit) string {
	sections := map[string][]entry{}
	for _, c := range commits {
		if section, e, ok := classify(c); ok {
			sections[section] = append(sections[section], e)
		}
	}

	title := releaseVersion
	if title == "" {
		title = "vX.Y.Z"
	}
	var b strings.Builder
	fmt.Fprintf(&b, "# Release %s\n\n", title)
	fmt.Fprintf(&b, "<!-- Draft generated by tools/release-notes from commits %s..%s. Verify every bullet against the diff and rewrite it per docs/standards/release-notes.md before publishing. -->\n\n", since, until)
	b.WriteString("## Upgrade\n\n")
	b.WriteString("<!-- Write the persona subsections from the diff: supported source version, minimum CLI version, operator-managed inputs, and required data migrations. -->\n")

	for _, name := range sectionOrder {
		entries := sections[name]
		if len(entries) == 0 {
			continue
		}
		fmt.Fprintf(&b, "\n## %s\n\n", name)
		for _, e := range entries {
			b.WriteString("- ")
			if e.Breaking {
				b.WriteString("**Breaking:** ")
			}
			b.WriteString(e.Summary)
			if e.Scope != "" {
				fmt.Fprintf(&b, " (%s, %s)", e.Scope, e.Hash)
			} else {
				fmt.Fprintf(&b, " (%s)", e.Hash)
			}
			b.WriteString("\n")
		}
	}
	return b.String()
}
