// Generates src/generated/select, the Genql types and type map behind the
// @livepeer-frameworks/api/select entry, from the public schema.
//
// Only the parts that build an operation and type its result are kept: the
// entry sends operations through the SDK client, so Genql's own client,
// fetcher, and batcher are left out. Genql writes extensionless relative
// imports; the package is native ESM, so each gets its .js extension.
// Trailing whitespace is stripped from every kept file.
import { mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

import { generate } from "@genql/cli";

const packageRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const schemaPath = resolve(packageRoot, "../pkg/graphql/public/schema.public.graphql");
const outputDir = join(packageRoot, "src/generated/select");

// The same TypeScript types codegen.ts maps these scalars to.
const scalarTypes = {
  ID: "string",
  Time: "string",
  JSON: "unknown",
  Currency: "string",
  Money: "string",
};

const keptFiles = [
  "schema.ts",
  "types.ts",
  "runtime/generateGraphqlOperation.ts",
  "runtime/linkTypeMap.ts",
  "runtime/typeSelection.ts",
  "runtime/types.ts",
];

const header =
  "/* Code generated by make graphql-sdk-ts from pkg/graphql/public/schema.public.graphql with Genql. DO NOT EDIT. */\n";

// Genql exports the type map as an untyped object literal, whose inferred
// type would be copied into the published declarations in full. Annotating
// it with the runtime's CompressedTypeMap keeps types.d.ts to one line.
function typedTypeMap(source) {
  if (!source.startsWith("export default {")) {
    throw new Error("select codegen: types.ts no longer starts with an exported object literal");
  }
  return (
    "import type { CompressedTypeMap } from './runtime/types.js'\n\n" +
    source.replace(/^export default \{/, "const types: CompressedTypeMap<number> = {") +
    "\n\nexport default types\n"
  );
}

const workDir = mkdtempSync(join(tmpdir(), "frameworks-genql-"));
try {
  await generate({ schema: schemaPath, output: workDir, scalarTypes });
  rmSync(outputDir, { recursive: true, force: true });
  for (const file of keptFiles) {
    const source = readFileSync(join(workDir, file), "utf8");
    let output = source.replace(
      /(from\s+['"])(\.{1,2}\/[^'"]+?)(['"])/g,
      (_match, open, path, close) => `${open}${path.endsWith(".js") ? path : `${path}.js`}${close}`
    );
    if (file === "types.ts") {
      output = typedTypeMap(output);
    }
    // Genql leaves trailing spaces on its empty JSDoc lines (" * ").
    output = output.replace(/[ \t]+$/gm, "");
    const target = join(outputDir, file);
    mkdirSync(dirname(target), { recursive: true });
    writeFileSync(target, header + output);
  }
} finally {
  rmSync(workDir, { recursive: true, force: true });
}
